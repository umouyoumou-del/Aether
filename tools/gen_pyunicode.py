"""Generate assets/rt/pyunicode_tables.go from the running CPython (use CPython 3.12: unicodedata 15.0.0).

    python3 tools/gen_pyunicode.py | gofmt > assets/rt/pyunicode_tables.go     # gofmt: the file in the tree is formatted

Every table is read off CPython's own str methods over all code points (surrogates excluded), so the Go side
does not depend on Go's unicode package (whose tables follow a newer Unicode version):

* pyAlpha / pyDecimal / pyDigit / pyNumeric / pySpace: where isalpha / isdecimal / isdigit / isnumeric /
  isspace hold (sorted inclusive ranges);
* pyLower: chr(c).lower() for every c it changes (U+0130 maps to two code points);
* pyCaseIgnorable / pyCasedNotIgnorable: the two properties lower() consults for the Greek final sigma,
  probed through lower() itself: X is case-ignorable iff ("AX"+"Σ").lower() ends in "ς" while ("X"+"Σ").lower()
  does not; X is cased (and not case-ignorable) iff ("X"+"Σ").lower() ends in "ς".
"""
import sys
import unicodedata

CPS = [c for c in range(0x110000) if not (0xD800 <= c <= 0xDFFF)]
SIGMA, FINAL = "Σ", "ς"


def ranges(pred):
    out, lo, prev = [], None, None
    for c in CPS:
        if pred(c):
            if lo is None:
                lo = c
            elif c != prev + 1:
                out.append((lo, prev))
                lo = c
            prev = c
        elif lo is not None:
            out.append((lo, prev))
            lo = None
    if lo is not None:
        out.append((lo, prev))
    return out


def table(name, rs):
    rows, row = [f"var {name} = [][2]rune{{"], []
    for a, b in rs:
        row.append(f"{{0x{a:X}, 0x{b:X}}},")
        if len(row) == 6:
            rows.append("\t" + " ".join(row))
            row = []
    if row:
        rows.append("\t" + " ".join(row))
    rows.append("}")
    return "\n".join(rows)


def main():
    ci, cased = set(), set()
    for c in CPS:
        x = chr(c)
        t1 = (x + SIGMA).lower()[-1] == FINAL
        t2 = ("A" + x + SIGMA).lower()[-1] == FINAL
        if t2 and not t1:
            ci.add(c)
        if t1:
            cased.add(c)
    out = [f"// Code generated by tools/gen_pyunicode.py from CPython {sys.version.split()[0]} "
           f"(unicodedata {unicodedata.unidata_version}); DO NOT EDIT.", "", "package rt", ""]
    for name, pred in (("pyAlpha", lambda c: chr(c).isalpha()), ("pyDecimal", lambda c: chr(c).isdecimal()),
                       ("pyDigit", lambda c: chr(c).isdigit()), ("pyNumeric", lambda c: chr(c).isnumeric()),
                       ("pySpace", lambda c: chr(c).isspace()), ("pyCaseIgnorable", lambda c: c in ci),
                       ("pyCasedNotIgnorable", lambda c: c in cased)):
        out += [table(name, ranges(pred)), ""]
    out.append("var pyLower = map[rune][]rune{")
    for c in CPS:
        low = chr(c).lower()
        if low != chr(c):
            out.append(f"\t0x{c:X}: {{" + ", ".join(f"0x{ord(x):X}" for x in low) + "},")
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
